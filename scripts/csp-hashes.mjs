// Postbuild: hash every inline <script> of every exported page and write an
// nginx map from the served file path to that page's hash list, so the
// Content-Security-Policy can drop 'unsafe-inline' from script-src.
//
// Next's static export inlines its bootstrap and RSC payload as <script>
// blocks whose content differs per page, so one global allowlist would grow
// with every page. nginx resolves `try_files` to the actual .html file, which
// sets $uri to that file's path; the map keys on it. Data blocks
// (application/ld+json, application/json) are not executed and need no hash.
// Anything not in the map (assets, unknown paths) gets no inline script at all.
//
// Usage: node scripts/csp-hashes.mjs <export dir> <output .conf>
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

const [outDir, confPath] = process.argv.slice(2);
if (!outDir || !confPath) {
  console.error("usage: csp-hashes.mjs <export dir> <output .conf>");
  process.exit(1);
}

const DATA_TYPES = new Set(["application/ld+json", "application/json"]);
const SCRIPT = /<script\b([^>]*)>([\s\S]*?)<\/script>/gi;

async function* htmlFiles(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* htmlFiles(p);
    else if (e.name.endsWith(".html")) yield p;
  }
}

function inlineHashes(html) {
  const hashes = new Set();
  for (const [, attrs, body] of html.matchAll(SCRIPT)) {
    if (/\bsrc\s*=/i.test(attrs)) continue;
    const type = /\btype\s*=\s*["']?([^"'\s>]+)/i.exec(attrs)?.[1]?.toLowerCase();
    if (type && DATA_TYPES.has(type)) continue;
    const digest = createHash("sha256").update(body, "utf8").digest("base64");
    hashes.add(`'sha256-${digest}'`);
  }
  return [...hashes];
}

// Inline event handler attributes cannot be allowed by a hash without
// 'unsafe-hashes'; fail the build instead of shipping a page that breaks.
const HANDLER = /<[a-z][^>]*\son[a-z]+\s*=/i;

const lines = [];
let pages = 0;
let total = 0;
for await (const file of htmlFiles(outDir)) {
  const html = await readFile(file, "utf8");
  if (HANDLER.test(html.replace(SCRIPT, ""))) {
    console.error(`csp-hashes: inline event handler in ${file}`);
    process.exit(1);
  }
  const hashes = inlineHashes(html);
  if (hashes.length === 0) continue;
  const uri = "/" + relative(outDir, file).split(sep).join("/");
  if (/["\\\s;{}]/.test(uri)) {
    console.error(`csp-hashes: unsupported character in ${uri}`);
    process.exit(1);
  }
  lines.push(`    "${uri}" "${hashes.join(" ")}";`);
  // A request for "/" reaches the root index through `try_files $uri/index.html`,
  // which leaves $uri as "//index.html".
  if (uri === "/index.html") lines.push(`    "//index.html" "${hashes.join(" ")}";`);
  pages++;
  total += hashes.length;
}

lines.sort();
const conf = `# Generated by scripts/csp-hashes.mjs at build time. Do not edit.
map_hash_bucket_size 256;
map_hash_max_size 8192;
map $uri $csp_script_hashes {
    default "";
${lines.join("\n")}
}
`;
await writeFile(confPath, conf);
console.log(`csp-hashes: ${total} hashes on ${pages} pages -> ${confPath}`);
